// Aliases
T.kht = T.khortha;

export function speak(text, lang) {
  try {
    window.speechSynthesis.cancel();
    const u = new SpeechSynthesisUtterance(text);
    if (lang === "khortha" || lang === "kht") {
      u.lang = "hi-IN";
      u.rate = 0.90;
      u.pitch = 1.05;
    } else if (lang === "hi") {
      u.lang = "hi-IN";
      u.rate = 0.95;
    } else {
      u.lang = "en-IN";
      u.rate = 0.95;
    }
    window.speechSynthesis.speak(u);
  } catch (e) {
    /* speech synthesis unavailable */
  }
}
